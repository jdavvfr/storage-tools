export function getLanguage(value) {
  return value === 'en' ? 'en' : 'fr'
}

export function translate(text, language = 'fr') {
  if (typeof text !== 'string') return text

  const dictionary = translations[language] ?? translations.fr
  if (Object.hasOwn(dictionary, text)) return dictionary[text]
  if (language !== 'en') return text

  const patterns = [
    [/^Groupe RAID ([56]) (\d+)$/, (_, level, index) => `RAID ${level} group ${index}`],
    [/^Miroir (\d+)$/, (_, index) => `Mirror ${index}`],
    [/^Disque de secours (\d+)$/, (_, index) => `Spare drive ${index}`],
    [/^(RAID (?:1|10)) nécessite un nombre pair de disques actifs$/, (_, raid) => `${raid} requires an even number of active drives`],
    [/^(RAID (?:50|60)) nécessite au moins (\d+) groupes$/, (_, raid, count) => `${raid} requires at least ${count} groups`],
    [/^Le nombre de groupes ne peut pas dépasser les (\d+) disques actifs$/, (_, count) => `The number of groups cannot exceed the ${count} active drives`],
    [/^(\d+) disques actifs ne sont pas divisibles en (\d+) groupes égaux$/, (_, drives, groups) => `${drives} active drives cannot be divided into ${groups} equal groups`],
    [/^Chaque groupe nécessite au moins (\d+) disques actifs$/, (_, count) => `Each group requires at least ${count} active drives`],
    [/^Charge ([\d,.]+) % · facteur domaine ×([\d,.]+)$/, (_, load, factor) => `Load ${load}% · group factor ×${factor}`],
    [/^(RAID \d+) nécessite au minimum (\d+) disques actifs$/, (_, raid, count) => `${raid} requires at least ${count} active drives`],
    [/^(\d+) hot spare(s?) disponible(s?)$/, (_, count) => `${count} hot spare${count === '1' ? '' : 's'} available`],
  ]
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(text)) return text.replace(pattern, replacement)
  }

  return text
    .replace(/\bGo\/s\b/g, 'GB/s')
    .replace(/\bMo\/s\b/g, 'MB/s')
    .replace(/\bGo\b/g, 'GB')
    .replace(/\bMo\b/g, 'MB')
    .replace(/\bTo\b/g, 'TB')
    .replace(/\bPo\b/g, 'PB')
}
